import assert from "node:assert/strict";
import { build } from "esbuild";

const result = await build({ entryPoints: ["source/app/wire-jumps.ts"], bundle: true, platform: "node", format: "esm", write: false });
const { bridgeMarker, bridgePath, findWireJumps } = await import(`data:text/javascript;base64,${Buffer.from(result.outputFiles[0].contents).toString("base64")}`);
const segment = (owner, x1, y1, x2, y2) => ({ owner, a: { x: x1, y: y1 }, b: { x: x2, y: y2 } });
const vertical = segment("vertical", 0, -40, 0, 40);
const horizontal = segment("horizontal", -40, 0, 40, 0);

assert.deepEqual(findWireJumps([vertical, horizontal], [], 7).map(({ x, y }) => [x, y]), [[0, 0]]);
assert.equal(findWireJumps([vertical, horizontal], [{ x: 0, y: 0 }], 7).length, 1, "a separate terminal at the crossing does not connect passing lines");
assert.equal(findWireJumps([segment("v", 0, 0, 0, 40), horizontal], [], 7).length, 1, "a passing line bridges an unconnected terminal");
assert.equal(findWireJumps([segment("v", 0, 0, 0, 40), horizontal], [{ x: 0, y: 0 }], 7).length, 1, "a connected terminal can still have an unrelated passing line");
assert.equal(findWireJumps([segment("v", 0, -40, 0, 0), segment("h", 0, 0, 40, 0)], [{ x: 0, y: 0 }], 7).length, 0, "joined endpoints have no bridge");
assert.equal(findWireJumps([segment("same", 0, -40, 0, 40), segment("same", -40, 0, 40, 0)], [], 7).length, 0, "a routed wire cannot bridge itself");
assert.equal(findWireJumps([vertical, segment("parallel", 10, -40, 10, 40)], [], 7).length, 0);
assert.equal(findWireJumps([vertical, horizontal, segment("nearby", -40, 10, 40, 10)], [], 7).length, 1, "bridges do not overlap");
assert.equal(findWireJumps([vertical, horizontal, segment("nearby", -40, 10, 40, 10), segment("far", -40, 20, 40, 20)], [], 7).length, 2, "a later crossing can still receive a bridge");
const wireOverPart = findWireJumps([{ ...vertical, wire: true }, { ...horizontal, owner: "part" }], [], 7)[0];
assert.equal(wireOverPart.over.owner, "vertical", "plain wires bridge over part leads");
const diagonal = segment("diagonal", -40, -40, 40, 40);
assert.deepEqual(findWireJumps([diagonal, horizontal], [], 7).map(({ x, y }) => [x, y]), [[0, 0]], "diagonal crossings also bridge");
const diagonalJump = findWireJumps([{ ...diagonal, wire: true }, horizontal], [], 7)[0];
const diagonalMarker = bridgeMarker({ x: 0, y: 0, dx: Math.SQRT1_2, dy: Math.SQRT1_2 }, [diagonalJump], 8, Math.PI / 2);
assert.ok(diagonalMarker.x > 0 && diagonalMarker.y < 0, "diagonal current follows the bridge");
assert.ok(Math.abs(Math.hypot(diagonalMarker.dx, diagonalMarker.dy) - 1) < 1e-8, "bridge marker direction stays normalized");
const angle = Math.PI / 2, radius = 8;
const jump = findWireJumps([vertical, horizontal], [], radius * Math.sin(angle))[0];
const bent = bridgePath([vertical.a, vertical.b], [jump], radius, angle);
assert.deepEqual([bent[0], bent.at(-1)], [vertical.a, vertical.b], "wire endpoints do not move");
assert.ok(Math.abs(Math.max(...bent.map((p) => p.x)) - radius) < 1e-8, "the bridge is a semicircle");
const middle = bridgeMarker({ x: 0, y: 0, dx: 0, dy: 1 }, [jump], radius, angle);
assert.ok(Math.abs(middle.x - Math.max(...bent.map((p) => p.x))) < 1e-8, "current markers follow the curved conductor");
const shoulder = bridgeMarker({ x: 0, y: -4, dx: 0, dy: 1 }, [jump], radius, angle);
assert.ok(shoulder.x > 0 && shoulder.dx > 0 && shoulder.dy > 0, "current markers turn with the upper shoulder");
const reverse = bridgeMarker({ x: 0, y: -4, dx: 0, dy: -1 }, [jump], radius, angle);
assert.ok(reverse.dx < 0 && reverse.dy < 0, "reverse current keeps its direction through the bridge");
assert.deepEqual(bridgeMarker({ x: 0, y: 25, dx: 0, dy: 1 }, [jump], radius, angle), { x: 0, y: 25, dx: 0, dy: 1 }, "markers away from bridges do not move");
console.log("Wire jump geometry passed.");
