// Verify the source and notices copied into the browser output and staged desktop apps.
// Run after npm run build; add --mac or --win after electron-builder has packaged the app.
import assert from "node:assert/strict";
import { existsSync, readFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { join } from "node:path";
import { createRequire } from "node:module";
import { checkReleaseSource } from "forge-shell/scripts/check-release";

const require = createRequire(import.meta.url);
const shellSpec = JSON.parse(readFileSync("package.json", "utf8")).dependencies?.["forge-shell"];
const archive = /^file:(source\/forge-shell-(\d+\.\d+\.\d+)\.tgz)$/.exec(shellSpec ?? "");
assert.ok(archive, "forge-shell must be pinned to a versioned package archive");
const shellLock = JSON.parse(readFileSync("package-lock.json", "utf8")).packages?.["node_modules/forge-shell"];
assert.equal(shellLock?.resolved, shellSpec, "forge-shell lockfile does not match the package archive");
assert.equal(shellLock?.version, archive[2], "forge-shell lockfile version differs from its pinned archive");
const integrity = `sha512-${createHash("sha512").update(readFileSync(archive[1])).digest("base64")}`;
assert.equal(shellLock?.integrity, integrity, "forge-shell package archive differs from the lockfile integrity");
assert.equal(readFileSync("node_modules/forge-shell/VERSION", "utf8").trim(), archive[2], "installed shell version differs from its pinned archive");
const { paths, copies, web, same } = checkReleaseSource({
  roots: ["source", "public", "assets", "scripts", "documentation"],
  files: ["LICENSE", "NOTICE.md", "README.md", "CHANGELOG.md", "VERSION", "forge.config.json", "package.json", "package-lock.json", "tsconfig.json"],
  releaseCopies: [{ from: "node_modules/forge-shell", to: "vendor/forge-shell" }],
  bannedWebFiles: ["xterm.css"],
  expectedDependencies: { "forge-shell": shellSpec },
});

// The licence text of every bundled package is generated by the build from the lockfile.
const licenseFile = join(web, "THIRD-PARTY-LICENSES.md");
assert.ok(existsSync(licenseFile), `missing ${licenseFile}`);
const licenseText = readFileSync(licenseFile, "utf8");
same(licenseFile, join(web, "release-source", "THIRD-PARTY-LICENSES.md"));
for (const [path, entry] of Object.entries(JSON.parse(readFileSync("package-lock.json", "utf8")).packages)) {
  const name = path.slice(path.lastIndexOf("node_modules/") + "node_modules/".length);
  if (path && !entry.dev && !entry.link && name !== "forge-shell") {
    assert.ok(licenseText.includes(name), `THIRD-PARTY-LICENSES.md does not list ${name}`);
  }
}

// The licence text of each borrowed work with its own terms ships beside the GPL text.
same("assets/licenses/ngspice-modified-bsd.txt", join(web, "licenses/ngspice-modified-bsd.txt"));

if (process.argv.includes("--mac")) {
  const resources = "build/release/mac-arm64/NodeForge.app/Contents/Resources";
  assert.ok(existsSync(resources), `missing ${resources}`);
  for (const path of paths) same(path, join(resources, "source", path));
  for (const [path, target] of copies) same(path, join(resources, "source", target));
  same("node_modules/electron/dist/LICENSE", join(resources, "licenses/ELECTRON_LICENSE"));
  same("node_modules/electron/dist/LICENSES.chromium.html", join(resources, "licenses/ELECTRON_CHROMIUM_LICENSES.html"));
  const asar = join(resources, "app.asar");
  const archive = require("@electron/asar");
  for (const path of ["LICENSE", "NOTICE.md", "CHANGELOG.md", "THIRD-PARTY-LICENSES.md"]) {
    assert.deepEqual(archive.extractFile(asar, join(web, path)), readFileSync(join(web, path)));
  }
  assert.throws(() => archive.extractFile(asar, join(web, "release-source", "README.md")),
    "source must be outside app.asar, in Resources/source");
  console.log("Mac app: source, GPL, notice, third-party licences, Electron and Chromium notices match.");
}

if (process.argv.includes("--win")) {
  const version = readFileSync("VERSION", "utf8").trim();
  const setup = join("build", "release", `NodeForge-v${version}.exe`);
  assert.ok(existsSync(setup), `missing Forge setup: ${setup}`);
  // The setup runs inside the app: its description is bundled beside the desktop main process.
  const setupConfig = JSON.parse(readFileSync("build/desktop/setup/setup.json", "utf8"));
  assert.equal(setupConfig.product, "NodeForge");
  assert.equal(setupConfig.version, version);
  assert.equal(setupConfig.extension, "nfg");
  assert.equal(setupConfig.documentIcon, "nodeforge-document.ico");
  const resources = "build/release/win-unpacked/resources";
  assert.ok(existsSync(resources), `missing ${resources}`);
  for (const path of paths) same(path, join(resources, "source", path));
  for (const [path, target] of copies) same(path, join(resources, "source", target));
  same("node_modules/electron/dist/LICENSE", join(resources, "licenses/ELECTRON_LICENSE"));
  // On Windows the Chromium notices ship once, beside the executable.
  same("node_modules/electron/dist/LICENSES.chromium.html", join("build/release/win-unpacked", "LICENSES.chromium.html"));
  assert.ok(existsSync(join(resources, "bin/nfsim.cjs")), "missing bundled nfsim");
  const archive = require("@electron/asar");
  const asar = join(resources, "app.asar");
  for (const path of ["LICENSE", "NOTICE.md", "CHANGELOG.md", "THIRD-PARTY-LICENSES.md"]) {
    assert.deepEqual(archive.extractFile(asar, join(web, path)), readFileSync(join(web, path)));
  }
  assert.throws(() => archive.extractFile(asar, join(web, "release-source", "README.md")),
    "source must be outside app.asar, in Resources/source");
  console.log("Windows app: source, GPL, notice, third-party licences, Electron and Chromium notices match.");
}
